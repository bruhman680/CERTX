def bound_expr(expr,target):
 try:
  def norm(s):
   tree=ast.parse(s.strip(),mode='eval')
   for n in ast.walk(tree):
    if isinstance(n,ast.Constant) and type(n.value) is float and n.value.is_integer():n.value=int(n.value)
    if isinstance(n,ast.BinOp) and isinstance(n.op,ast.Add) and ast.dump(n.left)>ast.dump(n.right):n.left,n.right=n.right,n.left
   return ast.dump(tree,include_attributes=False)
  return norm(expr)==norm(target)
 except (SyntaxError,ValueError):return False

